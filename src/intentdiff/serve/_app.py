def create_app(
    config: DiffConfig | None = None,
    differ: Any | None = None,  # SemanticDiffer | test mock
    cors_origins: list[str] | None = None,
) -> FastAPI:
    """Create and return the FastAPI playground application.

    Parameters
    ----------
    config:
        Optional :class:`~intentdiff.DiffConfig`.  Ignored when *differ*
        is supplied directly (useful for tests).
    differ:
        Optional pre-built :class:`~intentdiff.SemanticDiffer` (or any
        object with a ``.diff(source)`` method).  When ``None`` a fresh
        instance is created from *config*.
    cors_origins:
        Explicit list of allowed CORS origins.  When ``None`` (default) no
        CORS middleware is added — the API is not usable cross-origin.
        Pass ``["*"]`` only in development environments behind a firewall.
        Never use ``["*"]`` in production facing untrusted networks.
    """
    cfg = config or DiffConfig()
    _differ: Any = differ if differ is not None else SemanticDiffer(cfg)
    _html = _HTML_PATH.read_text(encoding="utf-8")

    # Semaphore to bound concurrent diff/detect computations.
    _sem = asyncio.Semaphore(8)

    app = FastAPI(
        title="IntentDiff Playground",
        description=(
            "Semantic code diff API.  "
            "`POST /diff` with `{old, new, language}` → SemanticDiff JSON."
        ),
        version="1.0.0",
        docs_url="/api/docs",
        redoc_url=None,
    )

    @app.middleware("http")
    async def _limit_body_size(request: Request, call_next):  # type: ignore[return]
        cl = request.headers.get("content-length")
        if cl is not None:
            try:
                if int(cl) > _MAX_REQUEST_BODY_BYTES:
                    return _request_body_too_large_response()
            except ValueError:
                pass

        chunks: list[bytes] = []
        total = 0
        async for chunk in request.stream():
            total += len(chunk)
            if total > _MAX_REQUEST_BODY_BYTES:
                return _request_body_too_large_response()
            chunks.append(chunk)
        body = b"".join(chunks)
        sent = False

        async def receive():  # type: ignore[no-untyped-def]
            nonlocal sent
            if sent:
                return {"type": "http.request", "body": b"", "more_body": False}
            sent = True
            return {"type": "http.request", "body": body, "more_body": False}

        request._body = body  # type: ignore[attr-defined]
        request._receive = receive  # type: ignore[attr-defined]
        return await call_next(request)

    if cors_origins is not None:
        app.add_middleware(
            CORSMiddleware,
            allow_origins=cors_origins,
            allow_methods=["GET", "POST"],
            allow_headers=["Content-Type", "Accept"],
            max_age=600,
        )

    # Mount vendored static assets (Monaco, etc.).
    # The vendor directory is optional at import time — it is populated by
    # running ``python scripts/vendor_monaco.py`` before serving.
    if _VENDOR_DIR.exists():
        app.mount(
            "/static/vendor",
            StaticFiles(directory=str(_VENDOR_DIR)),
            name="vendor",
        )

    # ── Routes ───────────────────────────────────────────────────────────────

    @app.get("/", response_class=HTMLResponse, include_in_schema=False)
    async def index() -> HTMLResponse:
        return HTMLResponse(content=_html, headers={"Content-Security-Policy": _CSP})

    @app.get("/static/playground.js", include_in_schema=False)
    async def playground_script() -> FileResponse:
        return FileResponse(
            _STATIC_DIR / "playground.js",
            media_type="application/javascript",
        )

    @app.get("/languages", summary="List supported languages")
    async def languages() -> dict[str, list[str]]:
        """Return all language IDs accepted by the ``/diff`` endpoint."""
        return {"languages": _supported_languages(_differ)}

    @app.get("/language-info", summary="List language and parser plugin metadata")
    async def language_info() -> dict[str, list[dict[str, Any]]]:
        """Return grouped language/plugin metadata for the playground UI."""
        return {"languages": _language_info(_differ)}

    @app.post("/diff", summary="Compute semantic diff")
    async def diff(req: DiffRequest) -> Response:
        """Compute a semantic diff between two code strings.

        Returns a **SemanticDiff** JSON object.  The response is stateless —
        no submitted code is stored.
        """
        try:
            async with _sem:
                if req.plugin_id:
                    result = await asyncio.to_thread(
                        _differ.diff_strings,
                        req.old,
                        req.new,
                        req.filename,
                        req.language,
                        parser_plugin_id=req.plugin_id,
                    )
                else:
                    source = StringSource(
                        req.old,
                        req.new,
                        filename=req.filename,
                        language_hint=req.language,
                    )
                    result = await asyncio.to_thread(_differ.diff, source)
        except PluginNotFoundError as exc:
            raise HTTPException(
                status_code=422,
                detail=f"Unknown language: {exc}",
            ) from exc
        except GrammarNotInstalledError as exc:
            raise HTTPException(
                status_code=422,
                detail=str(exc),
            ) from exc
        return Response(
            content=result.model_dump_json(),
            media_type="application/json",
        )

    # ── Detect endpoint ───────────────────────────────────────────────────

    @app.post("/detect", summary="Detect language from content")
    async def detect(req: DetectRequest) -> dict:
        """Return ranked language candidates detected by the registered parsers.

        Each parser's own Wasm ``detect-language`` function is consulted — no
        regex heuristics in Python.  The response is stateless.
        """
        try:
            async with _sem:
                if req.plugin_id:
                    results = await asyncio.to_thread(
                        _differ.detect_all,
                        req.content,
                        req.candidates,
                        req.preferred_plugins,
                        req.plugin_id,
                    )
                elif req.preferred_plugins:
                    results = await asyncio.to_thread(
                        _differ.detect_all,
                        req.content,
                        req.candidates,
                        req.preferred_plugins,
                    )
                else:
                    results = await asyncio.to_thread(
                        _differ.detect_all, req.content, req.candidates
                    )
        except PluginNotFoundError as exc:
            raise HTTPException(
                status_code=422,
                detail=f"Unknown parser plugin: {exc}",
            ) from exc
        top = results[0].language if results else None
        return {
            "language": top,
            "candidates": [
                {"language": r.language, "confidence": r.confidence}
                for r in results[:3]
            ],
        }

    @app.get("/example/{language}", summary="Fetch demo old/new example for a language")
    async def example(language: str, plugin_id: str | None = None) -> dict:
        """Return the ``old`` and ``new`` demo snippets for *language*.

        Each parser plugin supplies its own example via the WIT
        ``playground-example`` function.  Returns ``{"old": null, "new": null}``
        for unknown languages so the client can gracefully clear the editors.
        """
        if not _LANG_RE.fullmatch(language):
            raise HTTPException(
                status_code=422,
                detail="Invalid language identifier. "
                "Must be 1-64 alphanumeric/hyphen/dot/underscore characters.",
            )
        if plugin_id is not None and not _PLUGIN_ID_RE.fullmatch(plugin_id):
            raise HTTPException(
                status_code=422,
                detail="Invalid plugin identifier.",
            )
        try:
            if plugin_id:
                ex = await asyncio.to_thread(_differ.playground_example, language, plugin_id)
            else:
                ex = await asyncio.to_thread(_differ.playground_example, language)
        except PluginNotFoundError as exc:
            raise HTTPException(
                status_code=422,
                detail=f"Unknown parser plugin: {exc}",
            ) from exc
        if ex is None:
            return {"old": None, "new": None}
        return {"old": ex["old"], "new": ex["new"]}

    return app
